"""Trade watch: read a team's transaction wire on ESPN and raise a GitHub issue (the owner gets an email and a push
notification from GitHub) the first time a trade shows up. Run on every ticker beat until config.TRADE_WATCH['until'].

Owner's request, 2026-11-08: a notification as soon as the Giants make a trade before the 2026 deadline (Tuesday
2026-11-10, 4 pm ET). ESPN lists a trade once the league processes it, so the alert can trail the first news report.
"""
import datetime as dt
import json
import os
import re
from pathlib import Path

import requests

import config as C

SEEN = Path("watch/trade_seen.json")   # outside data/, which a failed beat reverts: an alert is never raised twice
URL = "https://site.api.espn.com/apis/site/v2/sports/football/nfl/transactions"
TRADE_RE = re.compile(r"\b(trade[ds]?|acquired)\b", re.I)


def fetch(espn_team_id):
    """The team's transactions as [(date, description)], newest first."""
    r = requests.get(URL, params={"team": espn_team_id}, timeout=20)
    r.raise_for_status()
    return [(t.get("date", ""), (t.get("description") or "").strip()) for t in r.json().get("transactions", []) if t.get("description")]


def new_trades(rows, seen):
    """Transactions not alerted before that read as a trade."""
    return [(d, s) for d, s in rows if f"{d}|{s}" not in seen and TRADE_RE.search(s)]


def open_issue(title, body):
    """A GitHub issue in this repository (the Actions token); the owner is mentioned so GitHub notifies them."""
    repo, token = os.environ.get("GITHUB_REPOSITORY"), os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if not repo or not token:
        print(f"watch: no GitHub token here; would have raised: {title}")
        return False
    r = requests.post(f"https://api.github.com/repos/{repo}/issues", timeout=20,
                      headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"},
                      json={"title": title, "body": body})
    if r.status_code >= 300:
        print(f"watch: issue not created (HTTP {r.status_code}: {r.text[:200]})")
        return False
    print(f"watch: issue raised: {r.json().get('html_url')}")
    return True


def run(now=None, test=False):
    w = C.TRADE_WATCH
    now = now or dt.datetime.now(dt.timezone.utc)
    if not test and now > dt.datetime.fromisoformat(w["until"]):
        return 0
    try:
        seen = set(json.loads(SEEN.read_text()))
    except (OSError, ValueError):
        seen = set()
    try:
        rows = fetch(w["espn_team_id"])
    except Exception as e:  # noqa: BLE001
        print(f"watch: ESPN transactions not reached ({type(e).__name__}); next beat retries")
        return 0
    if not seen:                                    # first run: what is already on the wire is not news
        SEEN.parent.mkdir(parents=True, exist_ok=True)
        SEEN.write_text(json.dumps(sorted(f"{d}|{s}" for d, s in rows), indent=1))
        print(f"watch: {w['team']} transaction wire read ({len(rows)} entries); watching for trades until {w['until']}")
        if not test:
            return 0
    hits = new_trades(rows, seen) if not test else [(rows[0][0] if rows else "", "TEST: this is what a trade alert looks like. No trade has happened.")]
    for d, s in hits:
        title = f"{w['team']} trade: {s[:90]}" if not test else f"{w['team']} trade watch: test alert"
        body = (f"@{w['notify']} {s}\n\nFrom ESPN's {w['team']} transaction wire ({d}), seen {now.strftime('%Y-%m-%d %H:%M')} UTC. "
                f"The model's projections pick up roster changes at the next daily run.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_")
        if open_issue(title, body) and not test:
            seen.add(f"{d}|{s}")
    if not test:
        seen |= {f"{d}|{s}" for d, s in rows if not TRADE_RE.search(s)}   # other moves are marked seen too
        SEEN.write_text(json.dumps(sorted(seen), indent=1))
    return len(hits)
