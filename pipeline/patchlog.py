"""The patch log for the site: every calibration, evaluation and change, read from MODEL_LOG.md and its archive.

Three kinds of entry: research and analysis sections (every "## " section from the first "## Research" up to the
standing watch, the post-mortems or the changelog, whichever comes first), weekly post-mortems ("### ..." under
"## Weekly post-mortems") and changelog entries ("### <when> (<what>)" under "## Changelog"). Newest first. The log
stays the record; this is a view of it, regenerated by every daily run. MODEL_LOG.md holds the current model, its
registers and the latest entries; MODEL_LOG_ARCHIVE.md holds the earlier ones in the same layout, so both are read.
"""
import re
from pathlib import Path

DATE_RE = re.compile(r"(20\d\d-\d\d-\d\d)")


def _sections(lines, level):
    """(heading, body lines) for each heading of the given level in `lines`, in file order."""
    out, head, body = [], None, []
    mark = "#" * level + " "
    for ln in lines:
        if ln.startswith(mark):
            if head is not None:
                out.append((head, body))
            head, body = ln[len(mark):].strip(), []
        elif head is not None:
            body.append(ln)
    if head is not None:
        out.append((head, body))
    return out


def _between(lines, start_pred, end_pred):
    out, on = [], False
    for ln in lines:
        if not on and start_pred(ln):
            on = True
            continue
        if on and end_pred(ln):
            break
        if on:
            out.append(ln)
    return out


def _entry(kind, head, body):
    text = "\n".join(body).strip("\n")
    date = DATE_RE.search(head)
    date = date.group(1) if date else (DATE_RE.search(text[:300]).group(1) if DATE_RE.search(text[:300]) else "")
    m = re.match(r"^(.*?)\s*\((.*)\)\s*$", head)
    if kind == "change" and m:
        when, what = m.group(1), m.group(2)
    else:
        when, what = (date, head)
    return dict(kind=kind, title=what, when=when, date=date, body=text)


STOPS = ("## Standing watch", "## Weekly post-mortems", "## Changelog", "## Ideas backlog", "## Known pitfalls")


def _parse(path):
    """Entries of one log file, in the order: changelog (file order, newest first), post-mortems and research (oldest first reversed)."""
    try:
        lines = Path(path).read_text().splitlines()
    except OSError:
        return []
    out = []
    # research and analysis: every "## " section from the first "## Research" up to the next part of the file
    res = _between(lines, lambda l: l.startswith("## Research"), lambda l: l.startswith(STOPS))
    first = next((l for l in lines if l.startswith("## Research")), None)
    if first is not None:
        res = [first] + res
    for head, body in _sections(res, 2):
        out.append(_entry("research", head, body))
    # post-mortems
    pm = _between(lines, lambda l: l.startswith("## Weekly post-mortems"), lambda l: l.startswith(("## Changelog", "## Ideas backlog", "## Known pitfalls")))
    for head, body in _sections(pm, 3):
        out.append(_entry("post-mortem", head, body))
    # changelog
    ch = _between(lines, lambda l: l.startswith("## Changelog"), lambda l: l.startswith(("## Ideas backlog", "## Known pitfalls")))
    for head, body in _sections(ch, 3):
        out.append(_entry("change", head, body))
    changes = [e for e in out if e["kind"] == "change"]              # file order is newest first
    pms = [e for e in out if e["kind"] == "post-mortem"][::-1]
    research = [e for e in out if e["kind"] == "research"][::-1]
    return changes + pms + research


def build(path="MODEL_LOG.md", archive=None):
    """Every entry of the log and of its archive (MODEL_LOG_ARCHIVE.md beside it, unless another path is given), newest
    first by date; within a date the main file comes first and changes keep their file order (sorted() is stable)."""
    archive = Path(archive) if archive else Path(path).with_name(Path(path).stem + "_ARCHIVE.md")
    return sorted(_parse(path) + _parse(archive), key=lambda e: e["date"] or "0000-00-00", reverse=True)
