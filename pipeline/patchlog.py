"""The patch log for the site: every calibration, evaluation and change, read from MODEL_LOG.md.

Three kinds of entry: research and analysis sections (the "## Research...", audit, risk pass and question sections
between the validation protocol and the standing watch), weekly post-mortems ("### ..." under "## Weekly
post-mortems") and changelog entries ("### <when> (<what>)" under "## Changelog"). Newest first. The log stays the
record; this is a view of it, regenerated by every daily run.
"""
import re
from pathlib import Path

DATE_RE = re.compile(r"(20\d\d-\d\d-\d\d)")


def _sections(lines, level):
    """(heading, body lines) for each heading of the given level in `lines`, in file order."""
    out, head, body = [], None, []
    mark = "#" * level + " "
    for ln in lines:
        if ln.startswith(mark):
            if head is not None:
                out.append((head, body))
            head, body = ln[len(mark):].strip(), []
        elif head is not None:
            body.append(ln)
    if head is not None:
        out.append((head, body))
    return out


def _between(lines, start_pred, end_pred):
    out, on = [], False
    for ln in lines:
        if not on and start_pred(ln):
            on = True
            continue
        if on and end_pred(ln):
            break
        if on:
            out.append(ln)
    return out


def _entry(kind, head, body):
    text = "\n".join(body).strip("\n")
    date = DATE_RE.search(head)
    date = date.group(1) if date else (DATE_RE.search(text[:300]).group(1) if DATE_RE.search(text[:300]) else "")
    m = re.match(r"^(.*?)\s*\((.*)\)\s*$", head)
    if kind == "change" and m:
        when, what = m.group(1), m.group(2)
    else:
        when, what = (date, head)
    return dict(kind=kind, title=what, when=when, date=date, body=text)


def build(path="MODEL_LOG.md"):
    lines = Path(path).read_text().splitlines()
    out = []
    # research and analysis: every "## " section from the first "## Research" up to "## Standing watch"
    res = _between(lines, lambda l: l.startswith("## Research"), lambda l: l.startswith("## Standing watch"))
    first = next((l for l in lines if l.startswith("## Research")), None)
    if first is not None:
        res = [first] + res
    for head, body in _sections(res, 2):
        out.append(_entry("research", head, body))
    # post-mortems
    pm = _between(lines, lambda l: l.startswith("## Weekly post-mortems"), lambda l: l.startswith("## Changelog"))
    for head, body in _sections(pm, 3):
        out.append(_entry("post-mortem", head, body))
    # changelog
    ch = _between(lines, lambda l: l.startswith("## Changelog"), lambda l: l.startswith("## Ideas backlog"))
    for head, body in _sections(ch, 3):
        out.append(_entry("change", head, body))
    # newest first: by date, then changelog/post-mortem file order (already newest first) and research reversed
    indexed = list(enumerate(out))
    changes = [e for _, e in indexed if e["kind"] == "change"]              # file order is newest first
    pms = [e for _, e in indexed if e["kind"] == "post-mortem"][::-1]
    research = [e for _, e in indexed if e["kind"] == "research"][::-1]
    merged = sorted(changes + pms + research, key=lambda e: e["date"] or "0000-00-00", reverse=True)
    # stable within a date: changes keep their file order (newest first), which sorted() preserves
    return merged
